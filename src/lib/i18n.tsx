const dicts = { en, fa };
export type TKey = keyof typeof en;

type Ctx = {
  lang: Lang;
  dir: "ltr" | "rtl";
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
  pick: <T>(v: { en: T; fa: T }) => T;
};

// Reuse one context across hot reloads so editing translations never splits
// the provider and its consumers into two different context instances.
const g = globalThis as { __migragoLangContext?: React.Context<Ctx | null> };
const LangContext = (g.__migragoLangContext ??= createContext<Ctx | null>(null));
const STORAGE_KEY = "migrago.lang";

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "fa" || stored === "en") setLangState(stored);
  }, []);

  useEffect(() => {
    const dir = lang === "fa" ? "rtl" : "ltr";
    document.documentElement.setAttribute("dir", dir);
    document.documentElement.setAttribute("lang", lang);
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem(STORAGE_KEY, l);
  }, []);

  const value = useMemo<Ctx>(
    () => ({
      lang,
      dir: lang === "fa" ? "rtl" : "ltr",
      setLang,
      t: (k: TKey) => dicts[lang][k] ?? en[k],
      pick: <T,>(v: { en: T; fa: T }) => v[lang],
    }),
    [lang, setLang],
  );

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useI18n must be used inside LanguageProvider");
  return ctx;
}

const faDigits = ["۰", "۱", "۲", "۳", "۴", "۵", "۶", "۷", "۸", "۹"];
export function localizeNumber(value: number | string, lang: Lang) {
  const s = String(value);
  if (lang !== "fa") return s;
  return s.replace(/\d/g, (d) => faDigits[Number(d)] ?? d);
}
